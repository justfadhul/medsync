-- ─────────────────────────────────────────────────────────────────────────
-- 0015_sa_audit_log
--
-- GATE F — superadmin god-mode + sensitive-elevation audit. Separate
-- from public.audit_log (which captures every CRUD via the trigger);
-- this is the HIGH-VISIBILITY log auditors look at first. Every
-- cross-tenant read, every approval, every superadmin elevation
-- lands here with a required `reason`.
--
-- Append-only by trigger (raises on UPDATE/DELETE) + REVOKE
-- UPDATE/DELETE from every role. Read access: superadmin only.
-- Write access: service-role only (Edge Functions).
--
-- NOT audited (a recursive audit trigger is pointless and noisy).
-- ─────────────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.sa_audit_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE SET NULL,
  action text NOT NULL,
  target_kind text NOT NULL,
  target_id text NOT NULL,
  reason text NOT NULL,
  request_id uuid,
  ip_address inet,
  user_agent text,
  before_data jsonb,
  after_data jsonb,
  timestamp timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT sa_audit_log_action_check
    CHECK (action IN (
      'approve_staff_affiliation',
      'reject_staff_affiliation',
      'approve_hospital_application',
      'reject_hospital_application',
      'cross_tenant_read',
      'cross_tenant_export',
      'elevate_admin',
      'create_superadmin',
      'demote_admin'
    )),
  CONSTRAINT sa_audit_log_target_kind_check
    CHECK (target_kind IN (
      'staff_affiliation','hospital_application','hospital','user','patient_profile'
    )),
  CONSTRAINT sa_audit_log_reason_min_len
    CHECK (length(trim(reason)) >= 8)
);

CREATE INDEX IF NOT EXISTS sa_audit_log_timestamp_idx
  ON public.sa_audit_log (timestamp DESC);
CREATE INDEX IF NOT EXISTS sa_audit_log_actor_idx
  ON public.sa_audit_log (actor_id);
CREATE INDEX IF NOT EXISTS sa_audit_log_target_idx
  ON public.sa_audit_log (target_kind, target_id);

-- ─── Append-only enforcement ─────────────────────────────────────────────

CREATE OR REPLACE FUNCTION public.sa_audit_log_block_mutation()
  RETURNS trigger
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path = public, pg_temp
AS $$
BEGIN
  RAISE EXCEPTION 'sa_audit_log is append-only';
END;
$$;

DROP TRIGGER IF EXISTS sa_audit_log_no_update ON public.sa_audit_log;
CREATE TRIGGER sa_audit_log_no_update
  BEFORE UPDATE ON public.sa_audit_log
  FOR EACH ROW EXECUTE FUNCTION public.sa_audit_log_block_mutation();

DROP TRIGGER IF EXISTS sa_audit_log_no_delete ON public.sa_audit_log;
CREATE TRIGGER sa_audit_log_no_delete
  BEFORE DELETE ON public.sa_audit_log
  FOR EACH ROW EXECUTE FUNCTION public.sa_audit_log_block_mutation();

-- Defence in depth: revoke direct UPDATE/DELETE at the privilege layer
-- so even a future role with table-owner intent can't accidentally
-- circumvent the trigger.
REVOKE UPDATE, DELETE ON public.sa_audit_log FROM PUBLIC;
REVOKE UPDATE, DELETE ON public.sa_audit_log FROM anon;
REVOKE UPDATE, DELETE ON public.sa_audit_log FROM authenticated;

-- ─── RLS ─────────────────────────────────────────────────────────────────

ALTER TABLE public.sa_audit_log ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sa_audit_log FORCE ROW LEVEL SECURITY;

-- SELECT: superadmin only. There's no UPDATE/DELETE/INSERT policy for
-- authenticated — write paths run via Edge Functions with the service
-- role (which bypasses RLS by design).
DROP POLICY IF EXISTS sa_audit_log_select_superadmin ON public.sa_audit_log;
CREATE POLICY sa_audit_log_select_superadmin
  ON public.sa_audit_log
  FOR SELECT
  TO authenticated
  USING (public.user_has_role('superadmin'));
